-- purchase_price/current_price були BIGINT (цілі копійки) — для акцій/
-- облігацій/депозитів цього достатньо, але меметокени (PEPE, SHIB,
-- BONK...) коштують частки копійки за 1 токен: округлення до цілого —
-- нуль. NUMERIC дозволяє дробову частину, при цьому всі попередні цілі
-- значення лишаються валідними (неявне приведення типу).
-- ============================================================
ALTER TABLE public.investments
  ALTER COLUMN purchase_price TYPE NUMERIC,
  ALTER COLUMN current_price TYPE NUMERIC;
